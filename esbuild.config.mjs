import esbuild from 'esbuild';
import process from 'process';
import { rename, rm, copyFile, appendFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { join } from 'node:path';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const outdir = '../NodusTestVault/.obsidian/plugins/nodus-ai';

// esbuild emits imported CSS next to the JS bundle as main.css;
// Obsidian expects it as styles.css in the plugin root.
const renameCss = {
	name: 'rename-css',
	setup(build) {
		build.onEnd(async (result) => {
			if (result.errors.length > 0) return;
			const generatedCss = join(outdir, 'main.css');
			const pluginStyles = join(outdir, 'styles.css');
			if (existsSync(generatedCss)) {
				await rename(generatedCss, pluginStyles);
			} else {
				await rm(pluginStyles, { force: true });
			}

			if (existsSync('manifest.json')) {
				await copyFile('manifest.json', join(outdir, 'manifest.json'));
			}

			// Create a .hotreload file in the plugin root to trigger hot reload in Obsidian
			// Install hot reload plugin is required for this to work
			if (!existsSync(join(outdir, '.hotreload'))) {
				await appendFile(join(outdir, '.hotreload'), '');
			}
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: { main: 'src/main.ts' },
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outdir: outdir,
	jsx: 'automatic',
	loader: {
		'.module.css': 'local-css',
	},
	define: {
		'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development'),
	},
	minify: prod,
	plugins: [renameCss],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
